def normalize(policy):
    """Keep exactly one price criterion, order by ordinal, and make the weights sum to 100."""
    crit = sorted(policy.get('criteria') or [], key=lambda c: c.get('ordinal', 99))
    if not any(c['kind'] == 'price' for c in crit):
        crit.insert(0, dict(DEFAULT_POLICY['criteria'][0]))
    seen_price = seen_scope = False
    for c in crit:
        if c['kind'] == 'price':
            c['kind'] = 'qualitative' if seen_price else 'price'
            seen_price = True
        elif c['kind'] == 'scope_completeness':
            c['kind'] = 'qualitative' if seen_scope else 'scope_completeness'
            seen_scope = True
        c['weight'] = max(0.0, float(c.get('weight') or 0))
        c['scale'] = sorted(c.get('scale') or [], key=lambda s: -s['points'])
    total = sum(c['weight'] for c in crit) or 1.0
    for c in crit:
        c['weight'] = round(c['weight'] / total * 100, 1)
    drift = round(100 - sum(c['weight'] for c in crit), 1)
    if crit and drift:
        crit[0]['weight'] = round(crit[0]['weight'] + drift, 1)
    for i, c in enumerate(crit, 1):
        c['ordinal'] = i
    policy['criteria'] = crit
    policy['gates'] = policy.get('gates') or []
    return policy


def generate(policy_text):
    out = llm.generate_json(POLICY_PROMPT.format(policy=policy_text[:60000]), POLICY_SCHEMA, kind='policy')
    out['source'] = 'ai'
    out['award_rule'] = award_rule(policy_text)
    return normalize(out)
